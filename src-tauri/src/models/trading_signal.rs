// ============================================================================
// TRADING SIGNAL MODEL
// ============================================================================
//
// Purpose: Data structures for trading signals emitted by the analyzer service.
//
// A TradingSignal represents a trading opportunity with a confidence score,
// target market, suggested size, and time-to-live. Signals flow from the
// analyzer to the executor via async channels.
//
// SIGNAL STRATEGIES:
//   arbitrage  - Price discrepancy between markets
//   momentum   - Significant price movement detected
//   sentiment  - News/social media analysis trigger
//
// Confidence score (0.0-1.0) feeds into Kelly criterion position sizing.
// Signals expire after ttl_ms if not executed.
// ============================================================================

use serde::{Deserialize, Serialize};
use serde_json::Value as JsonValue;
use crate::models::market::TradeSide;

/// Trading signal generated by the analyzer service
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TradingSignal {
    /// Unique identifier for this signal
    pub signal_id: String,
    
    /// Strategy that generated this signal: "arbitrage", "momentum", "sentiment"
    pub strategy: String,
    
    /// Confidence level (0.0-1.0) indicating signal strength
    pub confidence: f64,
    
    /// Target market ID for execution
    pub market_id: String,
    
    /// Trade direction (Buy YES or Buy NO)
    pub side: TradeSide,
    
    /// Suggested position size in contracts (executor may override)
    pub suggested_size: f64,
    
    /// Maximum acceptable slippage (e.g., 0.01 = 1%)
    pub max_slippage: f64,
    
    /// Unix timestamp when signal was generated
    pub timestamp: i64,
    
    /// Additional metadata (strategy-specific details)
    pub metadata: JsonValue,
    
    /// Time-to-live in milliseconds (signal expires after this duration)
    pub ttl_ms: u64,
}

impl TradingSignal {
    /// Create a new trading signal
    pub fn new(
        signal_id: String,
        strategy: String,
        confidence: f64,
        market_id: String,
        side: TradeSide,
        suggested_size: f64,
        max_slippage: f64,
        timestamp: i64,
        metadata: JsonValue,
        ttl_ms: u64,
    ) -> Self {
        Self {
            signal_id,
            strategy,
            confidence,
            market_id,
            side,
            suggested_size,
            max_slippage,
            timestamp,
            metadata,
            ttl_ms,
        }
    }
    
    /// Check if signal has expired
    pub fn is_expired(&self, current_time: i64) -> bool {
        current_time - self.timestamp > self.ttl_ms as i64
    }
    
    /// Validate signal fields
    pub fn is_valid(&self) -> bool {
        self.confidence >= 0.0 && self.confidence <= 1.0 &&
        self.max_slippage >= 0.0 && self.max_slippage <= 1.0 &&
        self.suggested_size > 0.0 &&
        !self.signal_id.is_empty() &&
        !self.strategy.is_empty() &&
        !self.market_id.is_empty()
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::models::market::TradeSide;
    
    #[test]
    fn test_create_trading_signal() {
        let signal = TradingSignal::new(
            "sig-123".to_string(),
            "arbitrage".to_string(),
            0.85,
            "polymarket-btc".to_string(),
            TradeSide::Buy,
            100.0,
            0.01,
            1704067200,
            serde_json::json!({"profit": 0.02}),
            5000,
        );
        
        assert_eq!(signal.signal_id, "sig-123");
        assert_eq!(signal.strategy, "arbitrage");
        assert_eq!(signal.confidence, 0.85);
        assert_eq!(signal.side, TradeSide::Buy);
    }
    
    #[test]
    fn test_signal_validity() {
        let valid_signal = TradingSignal::new(
            "sig-123".to_string(),
            "momentum".to_string(),
            0.75,
            "market-456".to_string(),
            TradeSide::Sell,
            50.0,
            0.02,
            1704067200,
            serde_json::json!({}),
            3000,
        );
        
        assert!(valid_signal.is_valid());
        
        let invalid_signal = TradingSignal::new(
            "".to_string(),  // Empty ID
            "momentum".to_string(),
            0.75,
            "market-456".to_string(),
            TradeSide::Sell,
            50.0,
            0.02,
            1704067200,
            serde_json::json!({}),
            3000,
        );
        
        assert!(!invalid_signal.is_valid());
    }
    
    #[test]
    fn test_signal_expiration() {
        let signal = TradingSignal::new(
            "sig-123".to_string(),
            "momentum".to_string(),
            0.75,
            "market-456".to_string(),
            TradeSide::Buy,
            50.0,
            0.02,
            1704067200,  // timestamp
            serde_json::json!({}),
            5000,  // 5 second TTL
        );
        
        // Within TTL
        assert!(!signal.is_expired(1704067202));
        
        // At TTL boundary
        assert!(!signal.is_expired(1704067205));
        
        // After TTL
        assert!(signal.is_expired(1704067210));
    }
}
